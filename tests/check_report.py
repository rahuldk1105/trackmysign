"""Check the verification report of `trackmysign verify --report` and `--json`.

Usage: python3 tests/check_report.py [--password=PW] <trackmysign> <signed.pdf> <out-dir> <expected text>...
Writes <out-dir>/<name>_verification.pdf and checks: qpdf --check passes,
pdftotext finds the title, file name, SHA-256 of the file, the summary line
and a heading per signature as in the JSON, the footer on every page, and
each expected text. The JSON must have the documented keys and agree with
the file (hash, size) and with itself (counts). The exit status must be 2
exactly when a signature is invalid or the content changed.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

args = sys.argv[1:]
pw_arg = [a for a in args if a.startswith("--password=")]
binary, path, out_dir, *expected = [a for a in args if not a.startswith("--password=")]
name = os.path.basename(path)
report = os.path.join(out_dir, name[:-4] + "_verification.pdf")
problems = []

run = subprocess.run([binary, "verify", *pw_arg, path, "--report", report, "--json"], capture_output=True, text=True)
try:
    doc = json.loads(run.stdout)
except json.JSONDecodeError:
    print("FAIL report", path, run.stdout, run.stderr)
    sys.exit(1)

data = open(path, "rb").read()
keys = {
    "": ["checked", "checked_at", "file", "generator", "not_checked", "schema", "schema_version", "signatures", "summary"],
    "file": ["encrypted", "name", "pages", "sha256", "size"],
    "summary": ["all_valid", "content_changed", "invalid", "signatures", "text", "unknown", "valid"],
}
for part, want in keys.items():
    got = sorted(doc[part] if part else doc)
    if got != want:
        problems.append(f"JSON {part or 'top level'} keys {got}")
if doc["schema"] != "trackmysign.verification-report" or doc["schema_version"] != 1:
    problems.append(f"schema {doc['schema']} {doc['schema_version']}")
if doc["file"]["sha256"] != hashlib.sha256(data).hexdigest() or doc["file"]["size"] != len(data):
    problems.append("JSON hash or size does not match the file")
sigs = doc["signatures"]
summary = doc["summary"]
statuses = [s["status"] for s in sigs]
if [summary["signatures"], summary["valid"], summary["invalid"], summary["unknown"]] != [
    len(sigs), statuses.count("valid"), statuses.count("invalid"), statuses.count("unknown")
]:
    problems.append(f"summary counts {summary}")
bad = "invalid" in statuses or any(s["coverage"]["changes"] == "content" for s in sigs)
if run.returncode != (2 if bad else 0):
    problems.append(f"exit status {run.returncode}: {run.stderr.strip()}")

check = subprocess.run(["qpdf", "--check", report], capture_output=True, text=True)
if check.returncode != 0:
    problems.append(f"qpdf --check: {check.stdout.strip()} {check.stderr.strip()}")
pages = subprocess.run(["pdfinfo", report], capture_output=True, text=True).stdout
pages = int(re.search(r"^Pages:\s+(\d+)", pages, re.M).group(1))
text = subprocess.run(["pdftotext", "-layout", "-enc", "UTF-8", report, "-"], capture_output=True, text=True).stdout
flat = " ".join(text.split())
want = [
    "Signature verification report",
    f"File {name}",
    f"SHA-256 {hashlib.sha256(data).hexdigest()}",
    summary["text"],
    "IST (",
    *expected,
]
for i, s in enumerate(sigs, 1):
    want.append(f"Signature {i} of {len(sigs)}: {s['status'].capitalize()}")
    want.append(f"Field {s['field']}")
for w in want:
    if " ".join(w.split()) not in flat:
        problems.append(f"report lacks {w!r}")
footers = len(re.findall(r"Generated by TrackMySign v\S+\. Checks", flat))
if footers != pages or f"Page {pages} of {pages}" not in flat:
    problems.append(f"{footers} footers on {pages} pages")
if "revocation (CRL/OCSP) and timestamp tokens are not checked" not in flat:
    problems.append("footer does not say what is not checked")

if problems:
    print("FAIL report", path)
    for p in problems:
        print("   -", p)
    sys.exit(1)
print(f"PASS report {name}: {summary['text']} ({pages} page{'s' if pages > 1 else ''})")
